/**
 * Clasifica una cuenta buscando el código exacto y, si no está, el prefijo
 * clasificado más largo. Devuelve null si no hay coincidencia (se aplica el
 * tratamiento por defecto del parser).
 */
export function clasificarGasto(codigo: string): ClaseGasto | null {
  const c = codigo.trim();
  for (let l = c.length; l >= 3; l--) {
    const m = CLASIFICACION_GASTOS[c.slice(0, l)];
    if (m) return m;
  }
  return null;
}
